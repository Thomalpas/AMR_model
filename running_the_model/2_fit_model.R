# -----------------------------------------------------------------------------
# Fit temporal hierarchical interval-censored MIC model
# -----------------------------------------------------------------------------
#
# Model summary:
#   - clone-level MIC observations are interval-censored on the log2 scale;
#   - patient-time sample means have a temporal regression with patient-specific
#     intercepts, trends and on/off oscillation effects;
#   - patient-level mean-MIC coefficients are modelled jointly;
#   - patient-level clone heterogeneity is kept in a separate log-SD hierarchy.
#   - growth rate gets an identical structure, now coupled through the random effects
#
# Expected project layout:
#   data/useable_cases.csv
#   stan_code/amr_coupled_temporal_mean_osc_offsets_separate_sigma.stan

library(cmdstanr)
library(tidyverse)
library(posterior)

# -----------------------------------------------------------------------------
# Paths and fixed settings
# -----------------------------------------------------------------------------

data_file <- "data/coupled_useable_cases.csv"
stan_file <- "stan_code/amr_pop_curve_only.stan"
out_dir <- "stan_output/amr_pop_curve_only"

# create output folder as needed
dir.create(out_dir, recursive = TRUE, showWarnings = FALSE)

# essential for the model
sigma_floor <- 0.05

# Oscillation coding. 
# off samples get -0.5, on samples are assigned +0.5.
on_weeks <- c(2, 12, 28, 44, 52)
off_weeks <- c(0, 16, 32, 48)
valid_weeks <- c(on_weeks, off_weeks)

# -----------------------------------------------------------------------------
# Read and check data
# -----------------------------------------------------------------------------

coupled_dat <- readr::read_csv(data_file, show_col_types = FALSE) |>
  janitor::clean_names()

# The input file generated by the earlier driver is already treatment-arm only,
# but this keeps the script safe if the wider clone-level file is passed in.
if ("trial_group" %in% names(coupled_dat)) {
  coupled_dat <- coupled_dat |>
    filter(trial_group == TRUE)
}

required_cols <- c(
  "patient_id", "time_id", "patient_time_id", "time_day", "time_week",
  "log2_mic_l", "log2_mic_u", "max_gr"
)

missing_cols <- setdiff(required_cols, names(coupled_dat))
if (length(missing_cols) > 0) {
  stop(
    "The input data are missing required columns: ",
    paste(missing_cols, collapse = ", ")
  )
}

coupled_dat <- coupled_dat |>
  mutate(
    patient_id = as.character(patient_id),
    time_id = as.character(time_id),
    patient_time_id = as.character(patient_time_id),
    time_day = as.numeric(time_day),
    time_week = as.numeric(time_week),
    log2_mic_l = as.numeric(log2_mic_l),
    log2_mic_u = as.numeric(log2_mic_u),
    lower_inf = is.infinite(log2_mic_l) & log2_mic_l < 0,
    upper_inf = is.infinite(log2_mic_u) & log2_mic_u > 0,
    cens_type = case_when(
      lower_inf & !upper_inf ~ 1L,  # left-censored: z <= U
      !lower_inf & upper_inf ~ 2L,  # right-censored: z > L
      !lower_inf & !upper_inf ~ 0L,
      TRUE ~ NA_integer_
    ),
    max_gr = as.numeric(max_gr)
  )

if (anyNA(coupled_dat$cens_type)) {
  stop("Some rows have unsupported censoring patterns.")
}

if (any(coupled_dat$cens_type == 0L & coupled_dat$log2_mic_u <= coupled_dat$log2_mic_l)) {
  stop("Some finite intervals have upper <= lower.")
}

if (any(coupled_dat$cens_type == 1L & !is.finite(coupled_dat$log2_mic_u))) {
  stop("Some left-censored rows do not have a finite upper bound.")
}

if (any(coupled_dat$cens_type == 2L & !is.finite(coupled_dat$log2_mic_l))) {
  stop("Some right-censored rows do not have a finite lower bound.")
}

observed_weeks <- sort(unique(coupled_dat$time_week))
unrecognised_weeks <- setdiff(observed_weeks, valid_weeks)
if (length(unrecognised_weeks) > 0) {
  stop(
    "Some observed weeks have no on/off coding: ",
    paste(unrecognised_weeks, collapse = ", ")
  )
}

# If no errors, input data has passed safety checks

# -----------------------------------------------------------------------------
# Create stable patient and patient-time sample keys
# -----------------------------------------------------------------------------

arrange_cols <- intersect(
  c("patient_id", "time_day", "time_week", "time_id", "patient_time_id"),
  names(coupled_dat)
)

coupled_dat <- coupled_dat |>
  arrange(across(all_of(arrange_cols)))

patient_key <- coupled_dat |>
  distinct(patient_id) |>
  arrange(patient_id) |>
  mutate(patient_index = row_number())

sample_key <- coupled_dat |>
  distinct(patient_time_id, patient_id, .keep_all = TRUE) |>
  arrange(across(all_of(arrange_cols))) |>
  select(patient_time_id, patient_id, time_id, time_day, time_week) |>
  left_join(patient_key, by = "patient_id") |>
  mutate(
    sample_index = row_number(),
    
    # Temporal covariates for the Stan model.
    on_off = case_when(
      time_week %in% on_weeks  ~  0.5,
      time_week %in% off_weeks ~ -0.5,
      TRUE ~ NA_real_
    )
  )

# Basic sanity checks for the temporal design.
if (anyNA(sample_key$on_off)) {
  bad <- sample_key |>
    filter(is.na(on_off)) |>
    distinct(time_week) |>
    pull(time_week)
  stop("Some samples have missing on_off coding: ", paste(bad, collapse = ", "))
}

cat("Temporal coding by observed week:\n")
sample_key |>
  distinct(time_week, on_off) |>
  arrange(time_week) |>
  print(n = Inf)
cat("\n")

coupled_dat <- coupled_dat |>
  left_join(patient_key, by = "patient_id") |>
  left_join(
    sample_key |> select(patient_time_id, sample_index),
    by = "patient_time_id"
  )

# Stan JSON cannot safely carry +/-Inf. Replace ignored bounds with dummy finite
# values. The censoring code tells Stan which bound to use.
coupled_dat <- coupled_dat |>
  mutate(
    L_stan = if_else(cens_type == 1L, 0, log2_mic_l),
    U_stan = if_else(cens_type == 2L, 0, log2_mic_u),
    mic_midpoint = case_when(
      cens_type == 0L ~ 0.5 * (log2_mic_l + log2_mic_u),
      cens_type == 1L ~ log2_mic_u - 0.5,
      cens_type == 2L ~ log2_mic_l + 0.5
    )
  )

if (any(!is.finite(coupled_dat$L_stan)) || any(!is.finite(coupled_dat$U_stan))) {
  stop("Non-finite bounds remain after censoring recode.")
}

# Aggregate identical observations within each patient-time sample.
# This is exactly equivalent to looping over clone-level rows and adding the
# same log probability repeatedly.
cell_dat <- coupled_dat |>
  count(sample_index, cens_type, L_stan, U_stan, name = "n_cell") |>
  arrange(sample_index, cens_type, L_stan, U_stan)

growth_dat <- coupled_dat |>
  arrange(sample_index)

stan_data <- list(
  
  # MIC likelihood
  M = nrow(cell_dat),
  sample_id_mic = cell_dat$sample_index,
  n_cell = cell_dat$n_cell,
  L = cell_dat$L_stan,
  U = cell_dat$U_stan,
  cens_type = cell_dat$cens_type,
  
  # Growth-rate likelihood
  N_gr = nrow(growth_dat),
  sample_id_gr = growth_dat$sample_index,
  growth_rate = growth_dat$max_gr,
  
  # Shared hierarchy
  S = nrow(sample_key),
  P = nrow(patient_key),
  
  patient_id_for_sample = sample_key$patient_index,
  
  time_week = sample_key$time_week,
  on_off = sample_key$on_off,
  
  sigma_floor = sigma_floor
)

cat("Data summary:\n",
"  clone-level observations:        ", nrow(coupled_dat), "\n",
"  aggregated sample-interval cells:", stan_data$M, "\n",
"  reduction factor:                ", round(nrow(coupled_dat) / stan_data$M, 2), "x\n",
"  patient-time samples:            ", stan_data$S, "\n",
"  patients:                        ", stan_data$P, "\n",
"  finite-interval clones:          ", sum(coupled_dat$cens_type == 0L), "\n",
"  left-censored clones:            ", sum(coupled_dat$cens_type == 1L), "\n",
"  right-censored clones:           ", sum(coupled_dat$cens_type == 2L), "\n",
"  time_4wk range:                  ", paste(range(sample_key$time_week), collapse = " to "), "\n",
"  sigma floor:                     ", sigma_floor, "\n\n")

saveRDS(stan_data, file.path(out_dir, "curved_stan_data_list.rds"))

# -----------------------------------------------------------------------------
# Compile and fit
# -----------------------------------------------------------------------------

mod <- cmdstan_model(stan_file)

# gives the model a starting point, doesn't effect the outcome hugely
init_alpha_mic <- median(coupled_dat$mic_midpoint, na.rm = TRUE)
init_alpha_gr <- median(coupled_dat$max_gr, na.rm = TRUE)

init_fun <- function() {
  list(
    pop_mean_coef = c(init_alpha_mic, init_alpha_mic, 0, 0, log(0.75), init_alpha_gr, init_alpha_gr, 0, 0, log(0.75)),
    tau_patient_mean_coef = c(0.5, 0.05, 2, 0.2, 0.5, 0.05, 0.2, 0.2),
    L_patient_mean_corr = diag(8),
    z_patient_mean_coef = matrix(0, nrow = 8, ncol = stan_data$P),
    tau_sample_mu_mic = 0.5,
    tau_sample_mu_gr = 0.5,
    z_sample_mu_mic = rep(0, stan_data$S),
    z_sample_mu_gr = rep(0, stan_data$S),
    tau_sample_log_sigma_mic = 0.2,
    z_sample_log_sigma_mic = rep(0, stan_data$S),
    tau_sample_log_sigma_gr = 0.2,
    z_sample_log_sigma_gr = rep(0, stan_data$S)
  )
}

fit <- mod$sample(
  data = stan_data,
  chains = 4,
  parallel_chains = 4,
  iter_warmup = 1000,
  iter_sampling = 1000,
  init = init_fun,
  adapt_delta = 0.95,
  max_treedepth = 12,
  refresh = 200
)

print(fit$summary(c(
  "pop_mean_coef",
  "tau_patient_coef",
  "tau_sample_mu_mic",
  "tau_sample_mu_gr",
  "tau_sample_log_sigma_mic",
  "tau_sample_log_sigma_gr",
  "patient_corr",
  "total_log_lik"
)), n = Inf)

# -----------------------------------------------------------------------------
# Save CmdStan outputs and key data objects
# -----------------------------------------------------------------------------

fit$save_output_files(dir = out_dir)
fit$save_data_file(dir = out_dir)
fit$save_object(file = file.path(out_dir, "amr_pop_curve_only_fit.rds"))

readr::write_csv(cell_dat, file.path(out_dir, "aggregated_mic_cells.csv"))
readr::write_csv(patient_key, file.path(out_dir, "patient_key.csv"))
readr::write_csv(sample_key, file.path(out_dir, "sample_key.csv"))
readr::write_csv(fit$summary(), file.path(out_dir, "full_posterior_summary.csv"))

# -----------------------------------------------------------------------------
# Lightweight patient- and sample-level summaries
# -----------------------------------------------------------------------------

index_summary <- function(fit, variable_name, key, index_col) {
  pat <- paste0("^", variable_name, "\\[(\\d+)\\]$")
  
  fit$summary(variable_name) |>
    mutate(
      .index = as.integer(stringr::str_match(variable, pat)[, 2])
    ) |>
    filter(!is.na(.index)) |>
    left_join(key, by = setNames(index_col, ".index"))
}

patient_summary <- bind_rows(
  index_summary(fit, "patient_alpha_base_mic", patient_key, "patient_index") |>
    mutate(quantity = "patient_mean_log2_mic_at_week0"),
  index_summary(fit, "patient_alpha_base_gr", patient_key, "patient_index") |>
    mutate(quantity = "patient_mean_gr_at_week0"),
  
  index_summary(fit, "patient_alpha_mid_mic", patient_key, "patient_index") |>
    mutate(quantity = "patient_mean_log2_mic_at_week52"),
  index_summary(fit, "patient_alpha_mid_gr", patient_key, "patient_index") |>
    mutate(quantity = "patient_mean_gr_at_week52"),
  
  index_summary(fit, "patient_oscillation_mic", patient_key, "patient_index") |>
    mutate(quantity = "patient_mic_on_minus_off"),
  index_summary(fit, "patient_oscillation_gr", patient_key, "patient_index") |>
    mutate(quantity = "patient_gr_on_minus_off"),
  
  index_summary(fit, "patient_log_excess_sigma_mic", patient_key, "patient_index") |>
    mutate(quantity = "patient_mic_log_excess_within_sample_clone_sd"),
  index_summary(fit, "patient_log_excess_sigma_gr", patient_key, "patient_index") |>
    mutate(quantity = "patient_gr_log_excess_within_sample_clone_sd"),
  
  index_summary(fit, "patient_typical_sigma_mic", patient_key, "patient_index") |>
    mutate(quantity = "patient_mic_typical_within_sample_clone_sd"),
  index_summary(fit, "patient_typical_sigma_gr", patient_key, "patient_index") |>
    mutate(quantity = "patient_gr_typical_within_sample_clone_sd")
)

sample_summary <- bind_rows(
  index_summary(fit, "sample_expected_mu_mic", sample_key, "sample_index") |>
    mutate(quantity = "sample_expected_mean_log2_mic"),
  index_summary(fit, "sample_expected_mu_gr", sample_key, "sample_index") |>
    mutate(quantity = "sample_expected_mean_gr"),
  
  index_summary(fit, "sample_mu_mic", sample_key, "sample_index") |>
    mutate(quantity = "sample_mean_log2_mic"),
  index_summary(fit, "sample_mu_gr", sample_key, "sample_index") |>
    mutate(quantity = "sample_mean_gr"),
  
  index_summary(fit, "sample_mean_residual_mic", sample_key, "sample_index") |>
    mutate(quantity = "sample_mean_residual_log2_mic"),
  index_summary(fit, "sample_mean_residual_gr", sample_key, "sample_index") |>
    mutate(quantity = "sample_mean_residual_gr"),
  
  index_summary(fit, "sample_log_excess_sigma_mic", sample_key, "sample_index") |>
    mutate(quantity = "sample_mic_log_excess_within_sample_clone_sd"),
  index_summary(fit, "sample_log_excess_sigma_gr", sample_key, "sample_index") |>
    mutate(quantity = "sample_gr_log_excess_within_sample_clone_sd"),
  
  index_summary(fit, "sample_sigma_mic", sample_key, "sample_index") |>
    mutate(quantity = "sample_mic_within_sample_clone_sd"),
  index_summary(fit, "sample_sigma_gr", sample_key, "sample_index") |>
    mutate(quantity = "sample_gr_within_sample_clone_sd")
)

readr::write_csv(patient_summary, file.path(out_dir, "patient_posterior_summary.csv"))
readr::write_csv(sample_summary, file.path(out_dir, "sample_posterior_summary.csv"))

cat("\nSaved outputs to: ", out_dir, "\n", sep = "")
